/**
 * Get a random inquiry from a category
 *
 * @param {string} category - Category name from CONSCIOUSNESS_INQUIRIES
 * @returns {string} A random inquiry
 */
function getRandomInquiry(category) {
    const inquiries = CONSCIOUSNESS_INQUIRIES[category];
    if (!inquiries) return THE_KEY_INSIGHT.question;

    const keys = Object.keys(inquiries);
    const randomKey = keys[Math.floor(Math.random() * keys.length)];

    // Handle nested structures (like elemental)
    const value = inquiries[randomKey];
    if (typeof value === 'string') {
        return value;
    } else if (typeof value === 'object') {
        const nestedKeys = Object.keys(value);
        const nestedKey = nestedKeys[Math.floor(Math.random() * nestedKeys.length)];
        return value[nestedKey];
    }
    return THE_KEY_INSIGHT.question;
}

/**
 * Get ritual by name
 *
 * @param {string} ritualName - Name of the ritual
 * @returns {Object|null} Ritual definition
 */
function getRitualByName(ritualName) {
    return Object.values(RESONANCE_RITUALS).find(
        r => r.name.toLowerCase() === ritualName.toLowerCase()
    ) || null;
}

/**
 * Get all inquiry categories
 *
 * @returns {Array} List of category names
 */
function getInquiryCategories() {
    return Object.keys(CONSCIOUSNESS_INQUIRIES);
}

/**
 * Count total inquiries
 *
 * @returns {number} Total number of inquiries
 */
function countTotalInquiries() {
    let count = 0;

    function countObject(obj) {
        for (const value of Object.values(obj)) {
            if (typeof value === 'string') {
                count++;
            } else if (typeof value === 'object' && value !== null) {
                countObject(value);
            }
        }
    }

    countObject(CONSCIOUSNESS_INQUIRIES);
    countObject(CENTERING_INQUIRIES);

    return count;
}

